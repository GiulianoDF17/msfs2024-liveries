/**
 * Returns the list of textures to include: only textures the user actually
 * painted (have an exported PNG). Unchanged textures come from the base
 * aircraft through texture.cfg fallbacks, which keeps downloads small.
 */
function texturesToInclude(project, projectDir) {
  return (project.textures || []).filter((t) => t.include !== false).map((t) => ({
    name: t.name,
    type: t.type,
    source: path.join(projectDir, 'textures', `${t.name}.PNG`),
  })).filter((t) => fs.existsSync(t.source));
}

/**
 * Checks a project before export. Returns { errors[], warnings[] }.
 * `knownTextureNames` = texture names found in the base aircraft.
 */
function preflight(project, projectDir) {
  const errors = [];
  const warnings = [];
  const d = project.details;
  if (!d.author || !d.author.trim()) errors.push('Author name is missing (Details screen).');
  if (!project.aircraft || !project.aircraft.folder) errors.push('This project has no base aircraft.');
  const included = texturesToInclude(project, projectDir);
  const painted = (project.textures || []).filter((t) => t.include !== false);
  if (painted.length === 0) warnings.push('No painted textures yet. The package will only change the name/registration.');
  for (const t of painted) {
    if (!included.find((i) => i.name === t.name)) errors.push(`Texture ${t.name} has not been saved yet. Open it in Paint and press Save.`);
  }
  const known = new Set(((project.aircraft && project.aircraft.textureNames) || []).map((t) => t.name.toUpperCase()));
  if (known.size > 0) {
    for (const t of painted) {
      if (!known.has(t.name.toUpperCase())) {
        warnings.push(`"${t.name}" is not a texture name of the base aircraft. It will not replace anything unless the name matches exactly.`);
      }
    }
  }
  if (project.aircraft && project.aircraft.modular) warnings.push('Modular aircraft liveries are EXPERIMENTAL. Test in the sim before publishing.');
  return { errors, warnings };
}

/** Writes build\ for the project. Returns details about what was written. */
function writeSdkProject(project, projectDir, opts = {}) {
  const highQuality = opts.highQuality !== false;
  const L = layout(project);
  const buildDir = path.join(projectDir, 'build');
  // Clean old sources so deleted textures don't linger. Keep compiled output.
  fs.rmSync(path.join(buildDir, 'PackageSources'), { recursive: true, force: true });
  fs.rmSync(path.join(buildDir, 'PackageDefinitions'), { recursive: true, force: true });
  fs.mkdirSync(buildDir, { recursive: true });

  const written = [];
  const write = (rel, content) => {
    const full = path.join(buildDir, ...rel.split('/'));
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, content);
    written.push(rel);
  };

  write('project.xml', projectXml(L.pkg));
  write(`PackageDefinitions/${L.pkg}.xml`, packageDefinitionXml(L.pkg, project, L.liveryRelDir));

  const src = `PackageSources/${L.liveryRelDir}`;
  const texDir = `PackageSources/${L.textureRelDir}`;
  if (L.mode === 'simple') {
    write(`${src}/aircraft.cfg`, aircraftCfg(project, L.texSuffix));
  } else {
    write(`${src}/livery.cfg`, liveryCfg(project));
  }
  write(`${texDir}/texture.cfg`, textureCfg(L.fallbacks));

  for (const t of texturesToInclude(project, projectDir)) {
    write(`${texDir}/${t.name}.PNG`, fs.readFileSync(t.source));
    write(`${texDir}/${t.name}.PNG.xml`, textureXml(t.type, highQuality));
  }

  // Thumbnail shown in the aircraft selection screen.
  const thumb = project.details.thumbnail && path.join(projectDir, project.details.thumbnail);
  if (thumb && fs.existsSync(thumb)) {
    write(`${texDir}/thumbnail.JPG`, fs.readFileSync(thumb));
    write(`PackageDefinitions/${L.pkg}/ContentInfo/Thumbnail.jpg`, fs.readFileSync(thumb));
  }

  return { ...L, buildDir, projectXml: path.join(buildDir, 'project.xml'), written };
}

