/**
 * Works out every path for a project. Returns:
 * { pkg, mode, liveryRelDir, textureRelDir, texSuffix, fallbacks[] }
 * Paths use forward slashes and are relative to PackageSources/ (and to the
 * package root after compiling).
 */
function layout(project) {
  const d = project.details;
  const a = project.aircraft;
  const pkg = packageName(d.author, a.folder, project.name);
  const category = a.category === 'Rotorcraft' ? 'Rotorcraft' : 'Airplanes';
  const texFolders = a.textureFolders && a.textureFolders.length ? a.textureFolders : ['texture'];
  const norm = (p) => String(p).replace(/\\/g, '/');

  if (a.modular) {
    const company = slugify(d.company || d.author, 32) || 'liveryforge';
    const livery = slugify(project.name, 40) || 'livery';
    const liveryRelDir = `SimObjects/${category}/${a.folder}/liveries/${company}/${livery}`;
    // From liveries/<company>/<livery>/texture back up to the aircraft root.
    const up = '..\\..\\..\\..\\';
    const fb = [];
    const fallbackList = (a.fallbackFolders && a.fallbackFolders.length)
      ? a.fallbackFolders
      : texFolders.filter((f) => /^common[\\/]texture$/i.test(norm(f)) || /^liveries\//i.test(norm(f))).slice(0, 2);
    for (const f of fallbackList) fb.push(up + norm(f).replace(/\//g, '\\'));
    return {
      pkg, mode: 'modular', liveryRelDir,
      textureRelDir: `${liveryRelDir}/texture`,
      texSuffix: '', fallbacks: fb,
    };
  }

  const texSuffix = textureSuffix(project.name);
  const liveryFolder = pkg;
  const liveryRelDir = `SimObjects/${category}/${liveryFolder}`;
  // texture.<X> sits in SimObjects/Airplanes/<ours>/, the base is a sibling.
  const fallbacks = [];
  const ordered = [...texFolders].sort((x, y) => (norm(x).toLowerCase() === 'texture' ? -1 : norm(y).toLowerCase() === 'texture' ? 1 : 0));
  if (!ordered.some((f) => norm(f).toLowerCase() === 'texture')) ordered.unshift('texture');
  for (const f of ordered) {
    if (/^liveries\//i.test(norm(f))) continue;
    fallbacks.push(`..\\..\\${a.folder}\\${norm(f).replace(/\//g, '\\')}`);
  }
  return {
    pkg, mode: 'simple', liveryRelDir,
    textureRelDir: `${liveryRelDir}/texture.${texSuffix}`,
    texSuffix, fallbacks,
  };
}

