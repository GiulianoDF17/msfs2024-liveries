/** Turns a raw fspackagetool log line into something a beginner understands. */
function friendlyLogLine(line) {
  const l = line.toLowerCase();
  if (/error/.test(l) && /texture|bitmap|png/.test(l)) return 'Texture error: check the texture size is a power of two (1024, 2048, 4096...) and the name matches the aircraft.';
  if (/access is denied|being used by another process/.test(l)) return 'A file is locked. Close MSFS 2024 (or the Community link) and try again.';
  if (/xml/.test(l) && /error/.test(l)) return 'An XML file could not be read. Re-export the project.';
  return null;
}

/**
 * Runs fspackagetool.exe. `onLog(level, text)` receives every line.
 * Resolves { ok, code, packageDir, errors[] }.
 * opts.command / opts.args let tests replace the real SDK tool.
 */
function compile({ sdkPath, projectXmlPath, steam = false, onLog = () => {}, command, args, timeoutMs = 30 * 60 * 1000 }) {
  return new Promise((resolve) => {
    const buildDir = path.dirname(projectXmlPath);
    let cmd = command;
    let cmdArgs = args;
    if (!cmd) {
      if (!isValidSdk(sdkPath)) {
        onLog('error', 'MSFS 2024 SDK not found. Open Settings and choose the SDK folder (it must contain Tools\\bin\\fspackagetool.exe).');
        resolve({ ok: false, code: -1, errors: ['SDK not found'] });
        return;
      }
      cmd = packageToolPath(sdkPath);
      cmdArgs = [projectXmlPath, '-rebuild', '-nopause'];
      if (steam) cmdArgs.push('-forcesteam');
    }
    onLog('info', `> "${cmd}" ${cmdArgs.map((a) => (a.includes(' ') ? `"${a}"` : a)).join(' ')}`);
    const errors = [];
    let child;
    try {
      child = spawn(cmd, cmdArgs, { cwd: buildDir, windowsHide: true });
    } catch (e) {
      onLog('error', `Could not start the SDK package tool: ${e.message}`);
      resolve({ ok: false, code: -1, errors: [e.message] });
      return;
    }
    const timer = setTimeout(() => {
      onLog('error', 'The SDK package tool took too long and was stopped.');
      try { child.kill(); } catch { /* ignore */ }
    }, timeoutMs);

    const handle = (chunk, isErr) => {
      for (const line of String(chunk).split(/\r?\n/)) {
        const text = line.trim();
        if (!text) continue;
        const isError = isErr || /\berror\b/i.test(text);
        const level = isError ? 'error' : /\bwarning\b/i.test(text) ? 'warn' : 'info';
        if (level === 'error') errors.push(text);
        onLog(level, text);
        const hint = level === 'error' ? friendlyLogLine(text) : null;
        if (hint) onLog('hint', hint);
      }
    };
    child.stdout.on('data', (c) => handle(c, false));
    child.stderr.on('data', (c) => handle(c, true));
    child.on('error', (e) => {
      clearTimeout(timer);
      onLog('error', `Could not run the SDK package tool: ${e.message}`);
      resolve({ ok: false, code: -1, errors: [e.message] });
    });
    child.on('close', (code) => {
      clearTimeout(timer);
      resolve({ ok: code === 0, code, errors });
    });
  });
}

