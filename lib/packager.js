const MARKER = '.liveryforge';

function lstatSafe(p) {
  try { return fs.lstatSync(p); } catch { return null; }
}

/**
 * Puts the package in Community.
 *  mode 'link' -> Windows directory junction (re-exports update instantly)
 *  mode 'copy' -> real copy (with a marker file so we know it's ours)
 */
function installToCommunity(packageDir, communityPath, mode = 'link') {
  if (!communityPath) throw new Error('Community folder is not set. Open Settings and press Auto-detect.');
  if (!fs.existsSync(packageDir)) throw new Error('Export the package first.');
  fs.mkdirSync(communityPath, { recursive: true });
  const name = path.basename(packageDir);
  const target = path.join(communityPath, name);
  const st = lstatSafe(target);
  if (st) {
    if (st.isSymbolicLink() || fs.existsSync(path.join(target, MARKER))) {
      removePath(target, st);
    } else {
      throw new Error(`A folder called "${name}" already exists in Community and was not made by Livery Forge. Remove it yourself first.`);
    }
  }
  if (mode === 'copy') {
    fs.cpSync(packageDir, target, { recursive: true });
    fs.writeFileSync(path.join(target, MARKER), 'Installed by Livery Forge');
  } else {
    // 'junction' works without admin rights on Windows. On other systems
    // (tests) Node ignores the type and makes a normal symlink.
    fs.symlinkSync(packageDir, target, 'junction');
  }
  return { target, mode };
}

function removePath(target, st) {
  if (st.isSymbolicLink()) {
    // Removing a junction/symlink only removes the link, never the real files.
    try { fs.unlinkSync(target); } catch { fs.rmdirSync(target); }
  } else {
    fs.rmSync(target, { recursive: true, force: true });
  }
}

/** Removes our package from Community. Only removes links or our own copies. */
function removeFromCommunity(pkg, communityPath) {
  if (!communityPath || !pkg) return { removed: false };
  const target = path.join(communityPath, pkg);
  const st = lstatSafe(target);
  if (!st) return { removed: false, reason: 'Not installed.' };
  if (st.isSymbolicLink() || fs.existsSync(path.join(target, MARKER))) {
    removePath(target, st);
    return { removed: true };
  }
  throw new Error('That Community folder was not created by Livery Forge, so it was left alone.');
}

/** Is the package currently in Community? Returns 'link' | 'copy' | 'other' | null */
function communityStatus(pkg, communityPath) {
  if (!communityPath || !pkg) return null;
  const target = path.join(communityPath, pkg);
  const st = lstatSafe(target);
  if (!st) return null;
  if (st.isSymbolicLink()) return 'link';
  if (fs.existsSync(path.join(target, MARKER))) return 'copy';
  return 'other';
}

