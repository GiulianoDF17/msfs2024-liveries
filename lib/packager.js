/** README.txt that goes inside the package. */
function readmeText(project) {
  const d = project.details;
  const out = [
    `${d.title || project.name}`,
    '='.repeat(Math.min(60, (d.title || project.name).length)),
    '',
    `Aircraft: ${project.aircraft.title}`,
    `Author:   ${d.author}`,
    `Version:  ${normalizeVersion(d.version)}`,
    '',
    d.description || d.shortDescription || '',
    '',
    'INSTALLATION',
    '------------',
    '1. Unzip this file.',
    '2. Drag the package folder into your MSFS 2024 Community folder.',
    '3. Start the sim and pick the livery in the aircraft selection screen.',
    '',
  ];
  if (d.readme) out.push('NOTES', '-----', d.readme, '');
  if (d.credits) out.push('CREDITS', '-------', d.credits, '');
  if (d.changelog) out.push('CHANGELOG', '---------', d.changelog, '');
  if (d.license) out.push('LICENSE', '-------', d.license, '');
  out.push('Made with Livery Forge.');
  return out.join('\r\n');
}

/** Fills manifest.json (creator, version, title) in a compiled package. */
function updateManifest(packageDir, project) {
  const file = path.join(packageDir, 'manifest.json');
  let m = {};
  try { m = JSON.parse(fs.readFileSync(file, 'utf8')); } catch { m = {}; }
  const d = project.details;
  m.dependencies = m.dependencies || [];
  m.content_type = m.content_type || 'LIVERY';
  m.title = d.title || project.name;
  m.manufacturer = d.manufacturer || project.aircraft.manufacturer || m.manufacturer || '';
  m.creator = d.author || m.creator || '';
  m.package_version = normalizeVersion(d.version);
  m.minimum_game_version = m.minimum_game_version || '1.0.0';
  m.release_notes = m.release_notes || { neutral: { LastUpdate: '', OlderHistory: '' } };
  fs.writeFileSync(file, JSON.stringify(m, null, 2));
  return m;
}

/** Zips a folder. The zip contains `rootName/` with the folder's content. */
function zipFolder(folder, zipPath, rootName) {
  return new Promise((resolve, reject) => {
    fs.mkdirSync(path.dirname(zipPath), { recursive: true });
    const out = fs.createWriteStream(zipPath);
    const zip = archiver('zip', { zlib: { level: 6 } });
    out.on('close', () => resolve({ path: zipPath, size: zip.pointer() }));
    zip.on('error', reject);
    zip.pipe(out);
    zip.directory(folder, rootName);
    zip.finalize();
  });
}

/**
 * After a successful compile: README + manifest + zip.
 * Returns { packageDir, zipPath, zipSize }.
 */
async function finishPackage(project, projectDir, outputRoot) {
  const L = layout(project);
  const packageDir = path.join(projectDir, 'build', 'Packages', L.pkg);
  if (!fs.existsSync(packageDir)) throw new Error('The compiled package was not found. The SDK build probably failed - check the log.');
  fs.writeFileSync(path.join(packageDir, 'README.txt'), readmeText(project));
  updateManifest(packageDir, project);
  const zipPath = path.join(outputRoot, `${L.pkg}_v${normalizeVersion(project.details.version)}.zip`);
  const z = await zipFolder(packageDir, zipPath, L.pkg);
  return { packageDir, zipPath, zipSize: z.size, pkg: L.pkg };
}

/**
 * "Source project only": zips build\ (without compiled output) so someone with
 * the SDK can compile it later.
 */
async function zipSourceProject(project, projectDir, outputRoot) {
  const L = layout(project);
  const buildDir = path.join(projectDir, 'build');
  const tmp = path.join(outputRoot, `.src-${L.pkg}`);
  fs.rmSync(tmp, { recursive: true, force: true });
  fs.mkdirSync(tmp, { recursive: true });
  for (const name of ['project.xml', 'PackageDefinitions', 'PackageSources']) {
    const s = path.join(buildDir, name);
    if (fs.existsSync(s)) fs.cpSync(s, path.join(tmp, name), { recursive: true });
  }
  fs.writeFileSync(path.join(tmp, 'HOW-TO-COMPILE.txt'), [
    'This is an MSFS 2024 SDK source project. MSFS 2024 cannot load it directly.',
    'Compile it with the MSFS 2024 SDK:',
    '  <SDK>\\Tools\\bin\\fspackagetool.exe "project.xml" -rebuild -nopause',
    `The finished package will be in Packages\\${L.pkg}.`,
  ].join('\r\n'));
  const zipPath = path.join(outputRoot, `${L.pkg}_source_v${normalizeVersion(project.details.version)}.zip`);
  const z = await zipFolder(tmp, zipPath, `${L.pkg}_source`);
  fs.rmSync(tmp, { recursive: true, force: true });
  return { zipPath, zipSize: z.size, pkg: L.pkg };
}

