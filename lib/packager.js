/**
 * packager.js
 * -----------
 * Turns a Livery Forge project into an MSFS 2024 package:
 *
 *  1. writeSdkProject()  -> writes an SDK project into <project>\build\
 *        build\project.xml
 *        build\PackageDefinitions\<package>.xml
 *        build\PackageSources\SimObjects\Airplanes\...  (cfg files + PNG + PNG.xml)
 *  2. compile()          -> runs fspackagetool.exe and streams the log
 *  3. finishPackage()    -> adds README.txt, fills manifest.json, makes the zip
 *  4. installToCommunity()/removeFromCommunity() -> link or copy into Community
 *
 * Two livery types are supported:
 *  - "simple" (classic / monolithic aircraft): a new aircraft folder that uses
 *    [VARIATION] base_container to borrow everything from the base aircraft.
 *  - "modular" (EXPERIMENTAL): a folder inside the base aircraft's liveries\
 *    folder with a livery.cfg.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');
const archiver = require('archiver');
const { slugify } = require('./safe-path');
const { packageToolPath, isValidSdk } = require('./msfs-paths');

/* ------------------------------------------------------------------ */
/* Names                                                               */
/* ------------------------------------------------------------------ */

/**
 * Package name = lowercase "author-aircraft-livery" slug.
 * MSFS needs every package name in the Community folder to be unique, so we
 * include all three parts. Max ~90 characters.
 */
function packageName(author, aircraftFolder, liveryName) {
  const parts = [slugify(author, 24) || 'liveryforge', slugify(aircraftFolder, 32) || 'aircraft', slugify(liveryName, 32) || 'livery'];
  return parts.join('-');
}

/** Texture folder suffix, e.g. "Delta N123" -> "DELTA_N123". */
function textureSuffix(liveryName) {
  return (slugify(liveryName, 32) || 'LIVERY').replace(/-/g, '_').toUpperCase();
}

/** Escapes text for XML. */
function xml(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&apos;');
}

/** Makes a value safe to put inside "quotes" in a .cfg file. */
function cfgStr(s) {
  return String(s == null ? '' : s).replace(/[\r\n]+/g, ' ').replace(/"/g, "'").trim();
}

/* ------------------------------------------------------------------ */
/* File contents                                                        */
/* ------------------------------------------------------------------ */

/** The SDK bitmap slot for each texture type. */
function bitmapSlot(type) {
  switch (type) {
    case 'comp': return 'MTL_BITMAP_METAL_ROUGH_AO';
    case 'normal': return 'MTL_BITMAP_NORMAL';
    case 'emissive': return 'MTL_BITMAP_EMISSIVE';
    case 'decal':
    case 'albedo':
    default: return 'MTL_BITMAP_DECAL0';
  }
}

/**
 * The small XML file that sits next to every PNG (e.g. FUSELAGE_ALBD.PNG.xml)
 * and tells the SDK how to compress the texture.
 */
function textureXml(type, highQuality = true) {
  const lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<BitmapConfiguration>',
    `  <BitmapSlot>${bitmapSlot(type)}</BitmapSlot>`,
  ];
  if (highQuality) lines.push('  <UserFlags type="_DEFAULT">QUALITYHIGH</UserFlags>');
  lines.push('</BitmapConfiguration>', '');
  return lines.join('\r\n');
}

/** aircraft.cfg for a simple (non-modular) livery. */
function aircraftCfg(project, texSuffix) {
  const d = project.details;
  const a = project.aircraft;
  const title = cfgStr(d.title || project.name);
  return [
    '; Generated by Livery Forge',
    '[VERSION]',
    'major = 1',
    'minor = 0',
    '',
    '[VARIATION]',
    `base_container = "..\\${a.folder}"`,
    '',
    '[FLTSIM.0]',
    `title = "${cfgStr(a.title)} ${title}"`,
    'model = ""',
    'panel = ""',
    'sound = ""',
    `texture = "${texSuffix}"`,
    `description = "${cfgStr(d.shortDescription || d.description).slice(0, 400)}"`,
    `ui_variation = "${title}"`,
    `ui_createdby = "${cfgStr(d.author)}"`,
    a.manufacturer ? `ui_manufacturer = "${cfgStr(a.manufacturer)}"` : null,
    a.model ? `ui_type = "${cfgStr(a.model)}"` : null,
    `atc_id = "${cfgStr(d.atcId)}"`,
    `atc_id_enable = ${d.atcId ? 1 : 0}`,
    `atc_airline = "${cfgStr(d.atcAirline)}"`,
    `icao_airline = "${cfgStr(d.icaoAirline)}"`,
    `atc_flight_number = "${cfgStr(d.flightNumber)}"`,
    `atc_parking_types = "${cfgStr(d.parkingTypes || 'RAMP')}"`,
    'isUserSelectable = 1',
    '',
  ].filter((l) => l !== null).join('\r\n');
}

/**
 * texture.cfg: tells MSFS where to find textures we did NOT change.
 * `fallbacks` are relative paths from our texture folder.
 */
function textureCfg(fallbacks) {
  const lines = ['[fltsim]'];
  fallbacks.forEach((f, i) => lines.push(`fallback.${i + 1}=${f}`));
  lines.push('');
  return lines.join('\r\n');
}

/** livery.cfg for a modular livery (EXPERIMENTAL). */
function liveryCfg(project) {
  const d = project.details;
  const lines = [
    '; Generated by Livery Forge (modular livery - experimental)',
    '[Version]',
    'major = 1',
    'minor = 0',
    '',
    '[General]',
    `name = "${cfgStr(d.title || project.name)}"`,
    '',
  ];
  if (d.requiredTags) {
    lines.push('[SELECTION]', `required_tags = "${cfgStr(d.requiredTags)}"`, '');
  }
  if (d.icaoAirline || d.atcId || d.parkingTypes) {
    lines.push('[FLTSIM.0]');
    if (d.icaoAirline) lines.push(`icao_airline = "${cfgStr(d.icaoAirline)}"`);
    if (d.atcId) lines.push(`atc_id = "${cfgStr(d.atcId)}"`);
    if (d.atcAirline) lines.push(`atc_airline = "${cfgStr(d.atcAirline)}"`);
    if (d.flightNumber) lines.push(`atc_flight_number = "${cfgStr(d.flightNumber)}"`);
    if (d.parkingTypes) lines.push(`atc_parking_types = "${cfgStr(d.parkingTypes)}"`);
    lines.push('');
  }
  return lines.join('\r\n');
}

/** The SDK project file passed to fspackagetool.exe. */
function projectXml(pkg) {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<Project Version="2" Name="${xml(pkg)}" FolderName="Packages" MetadataFolderName="PackagesMetadata">`,
    '  <OutputDirectory>.</OutputDirectory>',
    '  <TemporaryOutputDirectory>_PackageInt</TemporaryOutputDirectory>',
    '  <Packages>',
    `    <Package>PackageDefinitions\\${xml(pkg)}.xml</Package>`,
    '  </Packages>',
    '</Project>',
    '',
  ].join('\r\n');
}

/** PackageDefinitions\<pkg>.xml with one SimObject asset group. */
function packageDefinitionXml(pkg, project, liveryRelDir) {
  const d = project.details;
  const dir = liveryRelDir.replace(/\//g, '\\');
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<AssetPackage Name="${xml(pkg)}" Version="${xml(normalizeVersion(d.version))}">`,
    '  <ItemSettings>',
    '    <ContentType>LIVERY</ContentType>',
    `    <Title>${xml(d.title || project.name)}</Title>`,
    `    <Manufacturer>${xml(d.manufacturer || project.aircraft.manufacturer || '')}</Manufacturer>`,
    `    <Creator>${xml(d.author || '')}</Creator>`,
    '  </ItemSettings>',
    '  <Flags>',
    '    <VisibleInStore>false</VisibleInStore>',
    '    <CanBeReferenced>false</CanBeReferenced>',
    '  </Flags>',
    '  <AssetGroups>',
    '    <AssetGroup Name="livery">',
    '      <Type>SimObject</Type>',
    '      <Flags>',
    '        <FSXCompatibility>false</FSXCompatibility>',
    '      </Flags>',
    `      <AssetDir>PackageSources\\${dir}\\</AssetDir>`,
    `      <OutputDir>${dir}\\</OutputDir>`,
    '    </AssetGroup>',
    '  </AssetGroups>',
    '</AssetPackage>',
    '',
  ].join('\r\n');
}

/** "1.2" -> "1.2.0"; anything strange -> "1.0.0". */
function normalizeVersion(v) {
  const m = /^(\d+)(?:\.(\d+))?(?:\.(\d+))?/.exec(String(v || '').trim());
  if (!m) return '1.0.0';
  return `${m[1]}.${m[2] || 0}.${m[3] || 0}`;
}

